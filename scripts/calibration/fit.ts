/**
 * Fit relative Elo-style ratings to level-vs-level results and write src/engine/calibration.ts.
 * Usage: tsx scripts/calibration/fit.ts docs/calibration-games.*.jsonl
 *
 * Method: maximum-likelihood logistic (Elo) model with fractional scores (draw = 0.5), the weakest
 * level fixed at 0, plus ONE virtual drawn game between each pair of adjacent levels as a weak prior so that
 * 8-0 sweeps give a large-but-finite gap instead of infinity. Standard errors come from the Fisher information.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { LEVELS } from '../../src/engine/levels';

interface Row { a: string; b: string; scoreA: number; plies: number; how: string }
const files = process.argv.slice(2);
const rows: Row[] = files.flatMap((f) => readFileSync(f, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l) as Row));
const shipped = LEVELS.map((l) => l.id);
const extra = [...new Set(rows.flatMap((x) => [x.a, x.b]))].filter((id) => !shipped.includes(id));
// Bridges are listed between the shipped levels they were designed to link; the order only affects the prior below.
const ids = [...shipped, ...extra];
const n = ids.length;
const idx = (id: string) => ids.indexOf(id);

interface Obs { i: number; j: number; s: number; w: number }
const obs: Obs[] = rows.map((r) => ({ i: idx(r.a), j: idx(r.b), s: r.scoreA, w: 1 }));
// Weak prior: one virtual draw between each shipped level and the next one, and between each bridge and the shipped level 0 side.
for (let i = 0; i + 1 < shipped.length; i++) obs.push({ i, j: i + 1, s: 0.5, w: 1 });
for (let i = shipped.length; i < n; i++) obs.push({ i, j: 0, s: 0.5, w: 0.02 }); // negligible: only keeps the system solvable

const K = Math.LN10 / 400;
const expect = (d: number) => 1 / (1 + Math.exp(-K * d));

const r = new Array<number>(n).fill(0);
for (let it = 0; it < 200; it++) {
  const g = new Array<number>(n).fill(0);
  const H = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (const o of obs) {
    const e = expect(r[o.i]! - r[o.j]!);
    const grad = o.w * K * (o.s - e);
    const h = o.w * K * K * e * (1 - e);
    g[o.i]! += grad; g[o.j]! -= grad;
    H[o.i]![o.i]! += h; H[o.j]![o.j]! += h; H[o.i]![o.j]! -= h; H[o.j]![o.i]! -= h;
  }
  // fix level 0 at 0: solve on indices 1..n-1
  const m = n - 1;
  const A = Array.from({ length: m }, (_, a) => [...H[a + 1]!.slice(1), g[a + 1]!]);
  for (let c = 0; c < m; c++) {
    let p = c; for (let q = c + 1; q < m; q++) if (Math.abs(A[q]![c]!) > Math.abs(A[p]![c]!)) p = q;
    [A[c], A[p]] = [A[p]!, A[c]!];
    for (let q = 0; q < m; q++) if (q !== c) { const f = A[q]![c]! / A[c]![c]!; for (let k = c; k <= m; k++) A[q]![k]! -= f * A[c]![k]!; }
  }
  let maxStep = 0;
  for (let c = 0; c < m; c++) { const step = A[c]![m]! / A[c]![c]!; r[c + 1]! += step; maxStep = Math.max(maxStep, Math.abs(step)); }
  if (maxStep < 1e-6) break;
}

// Standard errors: invert the reduced Hessian.
const H = Array.from({ length: n }, () => new Array<number>(n).fill(0));
for (const o of obs) { const e = expect(r[o.i]! - r[o.j]!); const h = o.w * K * K * e * (1 - e); H[o.i]![o.i]! += h; H[o.j]![o.j]! += h; H[o.i]![o.j]! -= h; H[o.j]![o.i]! -= h; }
const m = n - 1;
const M = Array.from({ length: m }, (_, a) => [...H[a + 1]!.slice(1).map((v) => v), ...Array.from({ length: m }, (_, b) => (a === b ? 1 : 0))]);
for (let c = 0; c < m; c++) {
  let p = c; for (let q = c + 1; q < m; q++) if (Math.abs(M[q]![c]!) > Math.abs(M[p]![c]!)) p = q;
  [M[c], M[p]] = [M[p]!, M[c]!];
  const d = M[c]![c]!; for (let k = 0; k < 2 * m; k++) M[c]![k]! /= d;
  for (let q = 0; q < m; q++) if (q !== c) { const f = M[q]![c]!; for (let k = 0; k < 2 * m; k++) M[q]![k]! -= f * M[c]![k]!; }
}
const se = [0, ...Array.from({ length: m }, (_, a) => Math.sqrt(Math.max(0, M[a]![m + a]!)))];

// A shipped level is never presented as weaker than the one below it: when measurement noise says so
// (Expert and Maximum are statistically tied), the two are shown as equal instead of inverted.
for (let i = 1; i < shipped.length; i++) if (r[i]! < r[i - 1]!) r[i] = r[i - 1]!;

const games = rows.length;
const perLevel = ids.map((id) => rows.filter((x) => x.a === id || x.b === id).length);
const adj = shipped.slice(0, -1).map((id, i) => {
  const rs = rows.filter((x) => x.a === id && x.b === shipped[i + 1]);
  const score = rs.reduce((a, x) => a + x.scoreA, 0);
  return { from: id, to: shipped[i + 1]!, games: rs.length, scoreForLower: score };
});
const adjudicated = rows.filter((x) => x.how.startsWith('adjudicated')).length;

const out = `/**
 * GENERATED by scripts/calibration/fit.ts from docs/calibration-*.jsonl — do not edit by hand.
 *
 * What this is: relative strength of MoveWise's own bot levels measured by playing them (and measurement-only bridge opponents) against EACH OTHER
 * (${games} games, ${adjudicated} of them adjudicated by material or length), fitted with a logistic (Elo) model.
 * What this is NOT: a measurement against Stockfish, other engines, or human players. The absolute origin of the
 * scale is a convention (see profile/rating.ts), so these numbers say how far apart the levels are, not how
 * strong a "1200" is in FIDE or online terms. Time-limited levels also depend on how fast the device is.
 */
export const CALIBRATION = {
  generatedFor: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  games: ${games},
  adjudicated: ${adjudicated},
  /** Rating of each level relative to Complete Beginner = 0, in Elo-style points. */
  relative: ${JSON.stringify(Object.fromEntries(shipped.map((id, i) => [id, Math.round(r[i]!)])))} as Record<string, number>,
  /** One standard error of each relative rating, in points. */
  stdError: ${JSON.stringify(Object.fromEntries(shipped.map((id, i) => [id, Math.round(se[i]!)])))} as Record<string, number>,
  /** Games each level took part in. */
  gamesPerLevel: ${JSON.stringify(Object.fromEntries(shipped.map((id, i) => [id, perLevel[i]])))} as Record<string, number>,
} as const;
`;
writeFileSync('src/engine/calibration.ts', out);
console.log('games', games, 'adjudicated', adjudicated);
ids.forEach((id, i) => console.log(id.padEnd(13), String(Math.round(r[i]!)).padStart(6), '±' + Math.round(se[i]!), 'n=' + perLevel[i]));
console.log(JSON.stringify(adj));
